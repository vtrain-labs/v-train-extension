    /**
     * 統一語言偵測函式（可在任何上下文中呼叫）
     * 未來新增語言時，只需在此一處加入對映規則
     * @param {string} [navLang] - 自訂導航語言（如未傳入則自動讀取 navigator.language）
     * @returns {string} 語言 key，如 'en' / 'zh-TW' / 'zh-CN' / 'ja' 等
     */
    globalThis.detectLanguage = function detectLanguage(navLang) {
        const nav = (navLang || navigator.language || 'en').toLowerCase();
        if (nav.includes('zh-cn') || nav.includes('zh_cn')) return 'zh-CN';
        if (nav.includes('zh')) return 'zh-TW';
        if (nav.startsWith('ja')) return 'ja';
        if (nav.startsWith('ko')) return 'ko';
        if (nav.startsWith('es')) return 'es';
        if (nav.startsWith('fr')) return 'fr';
        if (nav.startsWith('de')) return 'de';
        return 'en';
    };

    /**
     * 核心翻譯替換函式
     * @param {string} lang - 使用者當前選擇的語言代碼 (e.g., 'en', 'zh-TW')
     * @param {string} key - 字典檔內的鍵值
     * @param {object} params - (選填) 需要替換的動態變數，例如 { idx: "3" }
     * @returns {string} 翻譯完成並替換完變數的字串
     */
    globalThis.getLangText = function getLangText(lang, key, params = {}) {
        // 1. 取得目標語系的字串，若找不到則回退 (Fallback) 至英文，再找不到則顯示 Key 本身
        let text = (VT_I18N[lang] && VT_I18N[lang][key]) ||
            (VT_I18N['en'] && VT_I18N['en'][key]) ||
            key;

        // 2. 如果傳入了參數，進行動態替換 (例如將 {idx} 替換為實際數字)
        if (params && typeof params === 'object') {
            for (const [pKey, pVal] of Object.entries(params)) {
                // 使用正則表達式全域替換，確保所有相同的 Placeholder 都被取代
                const regex = new RegExp(`\\{${pKey}\\}`, 'g');
                text = text.replace(regex, pVal);
            }
        }

        return text;
    }

